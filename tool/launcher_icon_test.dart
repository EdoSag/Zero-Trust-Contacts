// Draws the launcher icon from the suite's brand mark (ZtBrandMark): the
// brand indigo blending into Contacts pink, with the white contacts symbol.
// Run it again if the mark changes:
//   flutter test tool/launcher_icon_test.dart
import 'dart:io';
import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:zero_trust_core/zero_trust_core.dart';

const String res = 'android/app/src/main/res';
const Map<String, double> densities = <String, double>{
  'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4, //
};

Color get accentEnd =>
    Color.lerp(ZtTheme.brandSeed, ZtSuite.contacts.accent, 0.75)!;

Future<void> writePng(String path, int size,
    void Function(Canvas canvas, double size) paint) async {
  final ui.PictureRecorder recorder = ui.PictureRecorder();
  paint(Canvas(recorder), size.toDouble());
  final ui.Image image = await recorder.endRecording().toImage(size, size);
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  File(path).writeAsBytesSync(data!.buffer.asUint8List());
}

void paintSymbol(Canvas canvas, double size, double symbolSize) {
  final IconData icon = ZtSuite.contacts.icon;
  final TextPainter text = TextPainter(
    textDirection: TextDirection.ltr,
    text: TextSpan(
      text: String.fromCharCode(icon.codePoint),
      style: TextStyle(
          fontFamily: icon.fontFamily,
          fontSize: symbolSize,
          height: 1,
          color: Colors.white),
    ),
  )..layout();
  text.paint(canvas,
      Offset((size - text.width) / 2, (size - text.height) / 2));
}

void main() {
  testWidgets('launcher icon', (WidgetTester tester) async {
    await tester.runAsync(() async {
      final FontLoader font = FontLoader('MaterialIcons')
        ..addFont(File('${Platform.environment['FLUTTER_ROOT']}/bin/cache/'
                'artifacts/material_fonts/MaterialIcons-Regular.otf')
            .readAsBytes()
            .then((b) => ByteData.sublistView(b)));
      await font.load();

      for (final MapEntry<String, double> d in densities.entries) {
        // Older launchers: the whole rounded mark, 48dp.
        await writePng('$res/mipmap-${d.key}/ic_launcher.png',
            (48 * d.value).round(), (Canvas canvas, double size) {
          final Rect r = Offset.zero & Size(size, size);
          canvas.drawRRect(
            RRect.fromRectAndRadius(r, Radius.circular(size * 0.28)),
            Paint()
              ..shader = LinearGradient(
                begin: Alignment.topLeft,
                end: Alignment.bottomRight,
                colors: <Color>[ZtTheme.brandSeed, accentEnd],
              ).createShader(r),
          );
          paintSymbol(canvas, size, size * 0.5);
        });
        // Adaptive icons: the symbol on its own, 108dp with a 72dp safe
        // zone, so it's half of the visible part like on the mark.
        await writePng('$res/mipmap-${d.key}/ic_launcher_foreground.png',
            (108 * d.value).round(), (Canvas canvas, double size) {
          paintSymbol(canvas, size, size * 72 / 108 * 0.5);
        });
      }

      String hex(Color c) =>
          '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';
      Directory('$res/drawable').createSync(recursive: true);
      File('$res/drawable/ic_launcher_background.xml').writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- The brand mark's gradient. Generated by tool/launcher_icon_test.dart. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android">
    <gradient
        android:angle="315"
        android:startColor="${hex(ZtTheme.brandSeed)}"
        android:endColor="${hex(accentEnd)}" />
</shape>
''');
      Directory('$res/mipmap-anydpi-v26').createSync(recursive: true);
      File('$res/mipmap-anydpi-v26/ic_launcher.xml').writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
''');
    });
  });
}
